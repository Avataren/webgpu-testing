"""RenderDoc session manager: the open capture, its actions, resource names and passes."""

from __future__ import annotations

import os
import re

from renderdoc_mcp.util import rd, make_error, is_work, texture_size


class RenderDocSession:
    """Manages a single RenderDoc capture file's lifecycle."""

    def __init__(self):
        self._initialized: bool = False
        self._cap = None  # CaptureFile
        self._controller = None  # ReplayController
        self._filepath: str | None = None
        self._current_event: int | None = None
        self._action_map: dict[int, object] = {}
        self._structured_file = None
        self._resource_id_cache: dict[str, object] = {}  # str(resourceId) → resourceId
        self._texture_desc_cache: dict[str, object] = {}  # str(resourceId) → TextureDescription
        self._buffer_desc_cache: dict[str, object] = {}  # str(resourceId) → BufferDescription
        self._names: dict[str, str] = {}  # str(resourceId) → debug name
        self._passes: list[dict] | None = None

    def _ensure_initialized(self):
        """Initialize the replay system if not already done."""
        if not self._initialized:
            rd.InitialiseReplay(rd.GlobalEnvironment(), [])
            self._initialized = True

    @property
    def is_open(self) -> bool:
        return self._controller is not None

    @property
    def filepath(self) -> str | None:
        return self._filepath

    @property
    def controller(self):
        return self._controller

    @property
    def structured_file(self):
        return self._structured_file

    @property
    def current_event(self) -> int | None:
        return self._current_event

    @property
    def driver_name(self) -> str:
        """Get the API/driver name of the current capture."""
        return self._cap.DriverName() if self._cap else "unknown"

    @property
    def action_map(self) -> dict[int, object]:
        """Get the event_id -> ActionDescription mapping."""
        return self._action_map

    def require_open(self) -> dict | None:
        """Return an error dict if no capture is open, else None."""
        if not self.is_open:
            return make_error("No capture file is open. Use open_capture first.", "NO_CAPTURE_OPEN")
        return None

    def open(self, filepath: str) -> dict:
        """Open a .rdc capture file. Closes any previously open capture."""
        self._ensure_initialized()

        if not os.path.isfile(filepath):
            return make_error(f"File not found: {filepath}", "API_ERROR")

        if self.is_open:
            self.close()

        cap = rd.OpenCaptureFile()
        result = cap.OpenFile(filepath, "", None)
        if result != rd.ResultCode.Succeeded:
            cap.Shutdown()
            return make_error(f"Failed to open file: {result}", "API_ERROR")

        if not cap.LocalReplaySupport():
            cap.Shutdown()
            return make_error("Capture cannot be replayed on this machine", "API_ERROR")

        result, controller = cap.OpenCapture(rd.ReplayOptions(), None)
        if result != rd.ResultCode.Succeeded:
            cap.Shutdown()
            return make_error(f"Failed to initialize replay: {result}", "API_ERROR")

        self._cap = cap
        self._controller = controller
        self._filepath = filepath
        self._current_event = None
        self._structured_file = controller.GetStructuredFile()
        self._passes = None

        self._action_map = {}
        self._build_action_map(controller.GetRootActions())

        self._resource_id_cache = {}
        self._texture_desc_cache = {}
        self._buffer_desc_cache = {}
        self._names = {}
        textures = controller.GetTextures()
        buffers = controller.GetBuffers()
        for tex in textures:
            key = str(tex.resourceId)
            self._resource_id_cache[key] = tex.resourceId
            self._texture_desc_cache[key] = tex
        for buf in buffers:
            key = str(buf.resourceId)
            self._resource_id_cache[key] = buf.resourceId
            self._buffer_desc_cache[key] = buf
        for res in controller.GetResources():
            key = str(res.resourceId)
            self._resource_id_cache.setdefault(key, res.resourceId)
            if res.name and not res.autogeneratedName:
                self._names[key] = res.name

        return {
            "filepath": filepath,
            "api": cap.DriverName(),
            "total_actions": len(self._action_map),
            "draws": sum(1 for a in self._action_map.values() if a.flags & rd.ActionFlags.Drawcall),
            "dispatches": sum(1 for a in self._action_map.values() if a.flags & rd.ActionFlags.Dispatch),
            "passes": len(self.passes()),
            "textures": len(textures),
            "buffers": len(buffers),
            "named_resources": len(self._names),
        }

    def _build_action_map(self, actions):
        """Recursively index all actions by event_id."""
        for a in actions:
            self._action_map[a.eventId] = a
            if len(a.children) > 0:
                self._build_action_map(a.children)

    # ── Resources ──

    def resolve_resource_id(self, resource: str):
        """A ResourceId from "ResourceId::123", "123" or a resource's unique debug name."""
        resource = resource.strip()
        rid = self._resource_id_cache.get(resource)
        if rid is not None:
            return rid
        if resource.isdigit():
            return self._resource_id_cache.get(f"ResourceId::{resource}")
        matches = [key for key, name in self._names.items() if name == resource]
        if len(matches) == 1:
            return self._resource_id_cache.get(matches[0])
        return None

    def resource_key(self, resource: str) -> str | None:
        """The canonical "ResourceId::N" string for a resource reference, or None."""
        rid = self.resolve_resource_id(resource)
        return str(rid) if rid is not None else None

    def resource_error(self, resource: str) -> dict:
        matches = [key for key, name in self._names.items() if name == resource]
        if len(matches) > 1:
            return make_error(
                f"Several resources are named '{resource}': {', '.join(matches)}; pass an ID",
                "INVALID_RESOURCE_ID",
            )
        return make_error(f"Resource '{resource}' not found", "INVALID_RESOURCE_ID")

    def resource_name(self, resource_id) -> str:
        return self._names.get(str(resource_id), "")

    def get_texture_desc(self, resource_id_str: str):
        """Get a TextureDescription by resource ID string, or None."""
        return self._texture_desc_cache.get(resource_id_str)

    def get_buffer_desc(self, resource_id_str: str):
        return self._buffer_desc_cache.get(resource_id_str)

    def describe(self, resource_id) -> dict:
        """ID, debug name and size/format of a texture or buffer, for tool results."""
        key = str(resource_id)
        entry: dict = {"resource_id": key}
        name = self._names.get(key)
        if name:
            entry["name"] = name
        tex = self._texture_desc_cache.get(key)
        if tex is not None:
            entry["size"] = texture_size(tex)
            entry["format"] = str(tex.format.Name())
            if tex.arraysize > 1:
                entry["layers"] = tex.arraysize
        else:
            buf = self._buffer_desc_cache.get(key)
            if buf is not None:
                entry["bytes"] = buf.length
        return entry

    def label(self, resource_id) -> str:
        """Short readable label: the debug name, else the ID."""
        key = str(resource_id)
        return self._names.get(key) or key

    # ── Events ──

    def close(self) -> dict:
        """Close the current capture."""
        if not self.is_open:
            return {"status": "no capture was open"}

        filepath = self._filepath
        self._controller.Shutdown()
        self._cap.Shutdown()
        self._controller = None
        self._cap = None
        self._filepath = None
        self._current_event = None
        self._action_map = {}
        self._structured_file = None
        self._resource_id_cache = {}
        self._texture_desc_cache = {}
        self._buffer_desc_cache = {}
        self._names = {}
        self._passes = None
        return {"status": "closed", "filepath": filepath}

    def set_event(self, event_id: int) -> dict | None:
        """Navigate to a specific event. Returns error dict or None on success."""
        if event_id not in self._action_map:
            return make_error(f"Event ID {event_id} not found", "INVALID_EVENT_ID")
        if event_id != self._current_event:
            self._controller.SetFrameEvent(event_id, True)
            self._current_event = event_id
        return None

    def ensure_event(self, event_id: int | None) -> dict | None:
        """If event_id is given, set it. If no event is current, return error.
        Returns error dict or None on success."""
        if event_id is not None:
            return self.set_event(event_id)
        if self._current_event is None:
            return make_error("No event selected. Use set_event or pass event_id.", "INVALID_EVENT_ID")
        return None

    def get_action(self, event_id: int):
        """Get an ActionDescription by event_id, or None."""
        return self._action_map.get(event_id)

    def get_root_actions(self):
        return self._controller.GetRootActions()

    # ── Passes ──

    def passes(self) -> list[dict]:
        """The frame's passes, in order.

        wgpu wraps each render and compute pass in a debug-marker region named after the
        pass's label (with WGPU_DEBUG=1 in release builds), so the innermost marker
        regions that directly contain draws or dispatches are the passes. Work outside
        any marker is grouped by render-target changes instead.
        """
        if self._passes is not None:
            return self._passes
        sf = self._structured_file
        passes: list[dict] = []

        def add(name: str, marker_event: int | None, work: list) -> None:
            outputs: list[str] = []
            for a in work:
                for o in list(a.outputs) + [a.depthOut]:
                    key = str(o)
                    if int(o) != 0 and key not in outputs:
                        outputs.append(key)
            passes.append({
                "name": name,
                "marker_event": marker_event,
                "events": [a.eventId for a in work],
                "start_event": work[0].eventId,
                "end_event": work[-1].eventId,
                "draws": sum(1 for a in work if a.flags & rd.ActionFlags.Drawcall),
                "dispatches": sum(1 for a in work if a.flags & rd.ActionFlags.Dispatch),
                "outputs": outputs,
            })

        def walk(actions, marker_name: str | None, marker_event: int | None) -> None:
            direct: list = []
            for a in actions:
                if a.flags & rd.ActionFlags.PushMarker or (len(a.children) and not is_work(a)):
                    if direct:
                        flush(direct, marker_name, marker_event)
                        direct = []
                    is_marker = bool(a.flags & rd.ActionFlags.PushMarker)
                    walk(a.children,
                         a.GetName(sf) if is_marker else marker_name,
                         a.eventId if is_marker else marker_event)
                elif is_work(a):
                    direct.append(a)
            if direct:
                flush(direct, marker_name, marker_event)

        def flush(work: list, marker_name: str | None, marker_event: int | None) -> None:
            if marker_name is not None:
                add(marker_name, marker_event, work)
                return
            # No marker: split where the render targets change.
            group: list = []
            last: tuple | None = None
            for a in work:
                outs = tuple(str(o) for o in a.outputs if int(o) != 0)
                if group and outs != last:
                    add(_unnamed(group, sf), None, group)
                    group = []
                group.append(a)
                last = outs
            if group:
                add(_unnamed(group, sf), None, group)

        walk(self._controller.GetRootActions(), None, None)
        for index, p in enumerate(passes):
            p["index"] = index
        self._passes = passes
        return passes

    def find_passes(self, query: str | int | None) -> list[dict]:
        """Passes matching an index, an event inside them, or a name (case-insensitive regex)."""
        passes = self.passes()
        if query is None or query == "":
            return passes
        if isinstance(query, int) or (isinstance(query, str) and query.isdigit()):
            n = int(query)
            by_event = [p for p in passes if p["start_event"] <= n <= p["end_event"]
                        or p["marker_event"] == n]
            if by_event:
                return by_event
            return [p for p in passes if p["index"] == n]
        try:
            pattern = re.compile(query, re.IGNORECASE)
        except re.error:
            pattern = re.compile(re.escape(query), re.IGNORECASE)
        return [p for p in passes if pattern.search(p["name"])]

    def pass_of(self, event_id: int) -> dict | None:
        """The pass an event belongs to: by its draws and dispatches, else by the marker
        region around it (render-pass begin/end, clears, barriers)."""
        passes = self.passes()
        for p in passes:
            if event_id in p["events"]:
                return p
        action = self._action_map.get(event_id)
        while action is not None:
            if action.flags & rd.ActionFlags.PushMarker:
                for p in passes:
                    if p["marker_event"] == action.eventId:
                        return p
            action = action.parent
        return None

    def shutdown(self):
        """Full shutdown - close capture and deinitialize replay."""
        if self.is_open:
            self.close()
        if self._initialized:
            rd.ShutdownReplay()
            self._initialized = False


def _unnamed(work: list, sf) -> str:
    kind = "compute" if all(a.flags & rd.ActionFlags.Dispatch for a in work) else "draws"
    return f"({kind} at event {work[0].eventId}: {work[0].GetName(sf)})"


# Module-level singleton
_session: RenderDocSession | None = None


def get_session() -> RenderDocSession:
    """Get or create the global RenderDocSession singleton."""
    global _session
    if _session is None:
        _session = RenderDocSession()
    return _session
